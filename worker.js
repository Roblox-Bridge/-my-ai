/* SEND */

async function sendMessage() {

  const message =
    input.value.trim();

  if (!message) {

    input.focus();

    return;

  }

  if (
    sendButton.disabled
  ) {
    return;
  }

  sendButton.disabled =
    true;

  const welcome =
    document.getElementById(
      "welcome"
    );

  if (welcome) {
    welcome.remove();
  }

  addUserMessage(
    message
  );

  conversation.push({
    role: "user",
    content: message
  });

  input.value =
    "";

  input.style.height =
    "auto";

  addLoading();

  try {

    const controller =
      new AbortController();

    const timeout =
      setTimeout(
        () => {
          controller.abort();
        },
        90000
      );

    const response =
      await fetch(
        "/api/chat",
        {
          method: "POST",

          headers: {
            "Content-Type":
              "application/json",
            "Accept":
              "application/json"
          },

          body:
            JSON.stringify({
              message,
              history:
                conversation
            }),

          signal:
            controller.signal
        }
      );

    clearTimeout(
      timeout
    );

    const raw =
      await response.text();

    let data;

    try {

      data =
        JSON.parse(raw);

    } catch {

      throw new Error(
        "Invalid server response: " +
        raw.slice(0, 300)
      );

    }

    removeLoading();

    if (!response.ok) {

      throw new Error(
        data?.details ||
        data?.error ||
        "Request failed."
      );

    }

    if (!data?.reply) {

      throw new Error(
        "AI returned an empty response."
      );

    }

    addAIMessage(
      data.reply,
      data.sources || []
    );

    conversation.push({
      role: "assistant",
      content:
        data.reply
    });

  } catch (error) {

    removeLoading();

    let message =
      error?.message ||
      "Unknown error.";

    if (
      error?.name ===
      "AbortError"
    ) {

      message =
        "The request timed out. Please try again.";

    }

    addAIMessage(
      "⚠️ " + message
    );

  } finally {

    sendButton.disabled =
      false;

    input.focus();

  }

}

